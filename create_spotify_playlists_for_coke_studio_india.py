"""Create Spotify playlists for Coke Studio India/Bharat/Tamil songs, grouped by year.

Data source: Wikipedia song tables for Coke Studio @ MTV, Coke Studio Bharat, and
Coke Studio Tamil. Spotify matching uses the same fuzzy matcher as the HOS scraper.
"""

import argparse
import re
from collections import defaultdict
from typing import DefaultDict, Dict, List, Optional

import requests
from bs4 import BeautifulSoup
import spotipy
import spotipy.util as util

from create_spotify_playlist_for_hos_episode import (
    SCOPE,
    add_tracks_in_batches,
    create_playlist,
    find_spotify_tracks,
    load_spotify_config,
)


WIKI_BASE = "https://en.wikipedia.org/wiki/"
HEADERS = {"User-Agent": "Mozilla/5.0", "Accept": "text/html,application/xhtml+xml"}
PAGES = [
    ("Coke Studio @ MTV season 1", "Coke_Studio_@_MTV_season_1"),
    ("Coke Studio @ MTV season 2", "Coke_Studio_@_MTV_season_2"),
    ("Coke Studio @ MTV season 3", "Coke_Studio_@_MTV_season_3"),
    ("Coke Studio @ MTV season 4", "Coke_Studio_@_MTV_season_4"),
    ("Coke Studio Bharat", "Coke_Studio_Bharat"),
    ("Coke Studio Tamil", "Coke_Studio_Tamil"),
]


def clean_cell(value: str) -> str:
    value = re.sub(r"\[\s*\d+\s*\]", "", value or "")
    value = re.sub(r"\(\s*\d{4}-\d{2}-\d{2}\s*\)", "", value)
    value = value.strip().strip('"“”')
    return re.sub(r"\s+", " ", value).strip()


def extract_year(value: str) -> Optional[int]:
    match = re.search(r"\b(20\d{2}|201\d)\b", value or "")
    return int(match.group(1)) if match else None


def parse_coke_studio_page(edition: str, slug: str) -> List[Dict[str, str]]:
    url = WIKI_BASE + slug
    response = requests.get(url, headers=HEADERS, timeout=30)
    response.raise_for_status()
    soup = BeautifulSoup(response.text, "html.parser")

    rows: List[Dict[str, str]] = []
    for table in soup.find_all("table", class_="wikitable"):
        header_text = " ".join(th.get_text(" ", strip=True) for th in table.find_all("th")[:10]).lower()
        if "song title" not in header_text:
            continue

        current_year: Optional[int] = None
        for tr in table.find_all("tr"):
            cells = [clean_cell(cell.get_text(" ", strip=True)) for cell in tr.find_all(["td", "th"])]
            cells = [cell for cell in cells if cell]
            if not cells or "song title" in cells[0].lower() or cells[0].lower().startswith(("episode", "produced")):
                continue

            title = artist = date_text = ""
            if len(cells) >= 7:
                title, artist, date_text = cells[2], cells[3], cells[6]
                current_year = extract_year(date_text) or current_year
            elif len(cells) >= 4 and current_year:
                # Older @MTV pages omit episode/date cells for additional songs in
                # the same episode. Reuse the current episode year.
                title, artist = cells[0], cells[1]

            year = extract_year(date_text) or current_year
            if title and artist and year:
                rows.append({
                    "title": title,
                    "artist": artist,
                    "year": str(year),
                    "edition": edition,
                    "source": url,
                })

    return rows


def get_coke_studio_rows() -> List[Dict[str, str]]:
    rows: List[Dict[str, str]] = []
    seen = set()
    for edition, slug in PAGES:
        for row in parse_coke_studio_page(edition, slug):
            key = (row["year"], row["title"].lower(), row["artist"].lower())
            if key not in seen:
                seen.add(key)
                rows.append(row)
    return sorted(rows, key=lambda row: (row["year"], row["edition"], row["title"]))


def rows_by_year(rows: List[Dict[str, str]]) -> DefaultDict[str, List[Dict[str, str]]]:
    grouped: DefaultDict[str, List[Dict[str, str]]] = defaultdict(list)
    for row in rows:
        grouped[row["year"]].append(row)
    return grouped


def print_summary(grouped: Dict[str, List[Dict[str, str]]]):
    years = sorted(grouped)
    print(f"Coke Studio India/Bharat/Tamil has releases in {len(years)} calendar years: {', '.join(years)}")
    for year in years:
        print(f"{year}: {len(grouped[year])} songs")
        for row in grouped[year][:10]:
            print(f"  - {row['artist']} - {row['title']} [{row['edition']}]")


def update_year_playlist(sp, username: str, year: str, rows: List[Dict[str, str]], min_score: float, match_only: bool, overwrite: bool):
    print(f"\n=== {year} ===")
    track_ids = find_spotify_tracks(sp, rows, min_score=min_score)
    if match_only:
        print(f"Matched {len(track_ids)}/{len(rows)} Spotify tracks for {year}")
        return

    pl_name = f"Coke Studio India {year}"
    description = f"Coke Studio India/Bharat/Tamil songs from {year}, generated by APS"
    pl_id = create_playlist(sp, username, pl_name, description, overwrite=overwrite)
    add_tracks_in_batches(sp, username, pl_id, track_ids)
    print(f"Added {len(track_ids)}/{len(rows)} to playlist {pl_name}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--year", action="append", help="Only generate this year. Can be used multiple times.")
    parser.add_argument("--dry-run", action="store_true", help="Only scrape and print songs; do not use Spotify")
    parser.add_argument("--match-only", action="store_true", help="Search Spotify and print matches; do not create playlists")
    parser.add_argument("--min-score", type=float, default=0.62)
    parser.add_argument("--no-overwrite", action="store_true", help="Reuse existing playlists instead of replacing them")
    args = parser.parse_args()

    all_rows = get_coke_studio_rows()
    grouped = rows_by_year(all_rows)
    if args.year:
        wanted = set(args.year)
        grouped = defaultdict(list, {year: rows for year, rows in grouped.items() if year in wanted})

    print_summary(grouped)
    if args.dry_run:
        raise SystemExit(0)

    username = load_spotify_config()
    token = util.prompt_for_user_token(username, SCOPE)
    sp = spotipy.Spotify(auth=token, requests_timeout=20, retries=5)

    for year in sorted(grouped):
        update_year_playlist(sp, username, year, grouped[year], args.min_score, args.match_only, overwrite=not args.no_overwrite)
