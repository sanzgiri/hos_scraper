"""Create a Spotify playlist from an Echoes with John Diliberto playlist page."""

import argparse
import re
from typing import Dict, List, Optional, Tuple
from urllib.parse import urljoin

import requests
from bs4 import BeautifulSoup
import spotipy
import spotipy.util as util

from create_spotify_playlist_for_hos_episode import (
    SCOPE,
    add_tracks_in_batches,
    create_playlist,
    find_spotify_tracks,
    load_spotify_config,
)


BASE_URL = "https://echoes.org"
PLAYLIST_CATEGORY_URL = f"{BASE_URL}/category/playlists/"
HEADERS = {"User-Agent": "Mozilla/5.0", "Accept": "text/html,application/xhtml+xml"}


def _get_soup(url: str) -> BeautifulSoup:
    response = requests.get(url, headers=HEADERS, timeout=30)
    response.raise_for_status()
    return BeautifulSoup(response.text, "html.parser")


def get_latest_echoes_playlist_urls(limit: int = 1) -> List[str]:
    soup = _get_soup(PLAYLIST_CATEGORY_URL)
    urls: List[str] = []
    seen = set()
    for heading in soup.find_all(["h1", "h2", "h3"]):
        link = heading.find("a", href=True)
        if not link:
            continue
        title = link.get_text(" ", strip=True).lower()
        href = urljoin(BASE_URL, link["href"])
        if "echoes program" in title and href not in seen:
            seen.add(href)
            urls.append(href)
            if len(urls) >= limit:
                break
    return urls


def parse_echoes_playlist(url: str) -> Tuple[List[Dict[str, str]], str, str]:
    soup = _get_soup(url)
    title_tag = soup.find("h1")
    title = title_tag.get_text(" ", strip=True) if title_tag else url.rstrip("/").split("/")[-1]

    description = ""
    for paragraph in soup.find_all("p"):
        text = re.sub(r"\s+", " ", paragraph.get_text(" ", strip=True)).strip()
        if text and not text.lower().startswith(("homepage", "start time")):
            description = text
            break

    rows: List[Dict[str, str]] = []
    for tr in soup.find_all("tr"):
        cells = [re.sub(r"\s+", " ", cell.get_text(" ", strip=True)).strip() for cell in tr.find_all(["td", "th"])]
        if len(cells) != 4:
            continue
        start_time, artist, song, album = cells
        if start_time.lower() == "start time" or song.lower() == "song name":
            continue
        if not artist or not song or artist.lower() == "break" or song.lower() == "break":
            continue
        rows.append({"title": song, "artist": artist, "album": album, "start_time": start_time})

    print(f"Obtained {len(rows)} tracks for Echoes playlist: {title}")
    return rows, title, description


def playlist_name(title: str) -> str:
    cleaned = re.sub(r"\s+", " ", title).strip()
    cleaned = re.sub(r"^.*?–\s*", "", cleaned)
    return f"Echoes: {cleaned}"[:100]


def print_echoes_preview(rows: List[Dict[str, str]], title: str):
    print(title)
    for row in rows[:12]:
        album = f" [{row['album']}]" if row.get("album") else ""
        print(f"- {row['artist']} - {row['title']}{album}")


def dedupe_rows(rows: List[Dict[str, str]]) -> List[Dict[str, str]]:
    deduped: List[Dict[str, str]] = []
    seen = set()
    for row in rows:
        key = (row.get("artist", "").strip().lower(), row.get("title", "").strip().lower())
        if key not in seen:
            seen.add(key)
            deduped.append(row)
    return deduped


def run_echoes_combined(urls: List[str], sp: Optional[spotipy.Spotify], username: str, dry_run: bool, match_only: bool, min_score: float, overwrite: bool):
    all_rows: List[Dict[str, str]] = []
    titles: List[str] = []
    for url in urls:
        rows, title, _ = parse_echoes_playlist(url)
        titles.append(title)
        for row in rows:
            row["episode"] = title
        all_rows.extend(rows)

    rows = dedupe_rows(all_rows)
    print(f"Echoes Recent: {len(rows)} unique tracks from {len(urls)} playlists ({len(all_rows)} total rows)")
    print_echoes_preview(rows, "Echoes Recent")

    if dry_run:
        return

    track_ids = find_spotify_tracks(sp, rows, min_score=min_score)
    if match_only:
        print(f"Matched {len(track_ids)}/{len(rows)} Spotify tracks")
        return

    description = f"Tracks from the latest {len(urls)} Echoes playlists, generated by APS"
    pl_id = create_playlist(sp, username, "Echoes Recent", description, overwrite=overwrite)
    add_tracks_in_batches(sp, username, pl_id, track_ids)
    print(f"Added {len(track_ids)}/{len(rows)} to playlist Echoes Recent")


def run_echoes_playlist(url: str, sp: Optional[spotipy.Spotify], username: str, dry_run: bool, match_only: bool, min_score: float, overwrite: bool):
    rows, title, description = parse_echoes_playlist(url)
    print_echoes_preview(rows, title)

    if dry_run:
        return

    track_ids = find_spotify_tracks(sp, rows, min_score=min_score)
    if match_only:
        print(f"Matched {len(track_ids)}/{len(rows)} Spotify tracks")
        return

    pl_name = playlist_name(title)
    pl_id = create_playlist(sp, username, pl_name, description, overwrite=overwrite)
    add_tracks_in_batches(sp, username, pl_id, track_ids)
    print(f"Added {len(track_ids)}/{len(rows)} to playlist {pl_name}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("urls", nargs="*", help="Echoes playlist page URL(s). If omitted, uses latest playlist page.")
    parser.add_argument("--latest", type=int, default=1, help="Number of latest Echoes playlists to use when no URL is provided")
    parser.add_argument("--combined", action="store_true", help="Create/update one combined 'Echoes Recent' playlist from all selected URLs")
    parser.add_argument("--dry-run", action="store_true", help="Only scrape and print Echoes tracks; do not use Spotify")
    parser.add_argument("--match-only", action="store_true", help="Search Spotify and print matches; do not create a playlist")
    parser.add_argument("--min-score", type=float, default=0.62, help="Minimum fuzzy match score, from 0.0 to 1.0")
    parser.add_argument("--no-overwrite", action="store_true", help="Reuse an existing playlist instead of replacing it")
    args = parser.parse_args()

    urls = args.urls or get_latest_echoes_playlist_urls(args.latest)
    if not urls:
        parser.error("No Echoes playlist URLs found")

    if args.dry_run:
        sp = None
        username = ""
    else:
        username = load_spotify_config()
        token = util.prompt_for_user_token(username, SCOPE)
        sp = spotipy.Spotify(auth=token, requests_timeout=20, retries=5)

    if args.combined:
        run_echoes_combined(
            urls=urls,
            sp=sp,
            username=username,
            dry_run=args.dry_run,
            match_only=args.match_only,
            min_score=args.min_score,
            overwrite=not args.no_overwrite,
        )
    else:
        for url in urls:
            run_echoes_playlist(
                url=url,
                sp=sp,
                username=username,
                dry_run=args.dry_run,
                match_only=args.match_only,
                min_score=args.min_score,
                overwrite=not args.no_overwrite,
            )
